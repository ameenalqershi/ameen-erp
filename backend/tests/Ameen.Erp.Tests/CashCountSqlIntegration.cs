using Ameen.Erp.Domain;
using Ameen.Erp.Infrastructure;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;

namespace Ameen.Erp.Tests;

// CASH11-01 accepts only the structural foundation, on a disposable SQL database.
// Neither count approval nor drawer balance or journal is implemented here.
public static class CashCountSqlIntegration
{
    public static async Task Upgrade(ErpDbContext db)
    {
        var script = await File.ReadAllTextAsync(Path.Combine(
            AppContext.BaseDirectory, "database", "033_cash_counts_foundation.sql"));

        // A failure after creating the parent must undo both the DDL and the
        // version receipt; no partial schema can be accepted as upgraded.
        await db.Database.ExecuteSqlRawAsync("CREATE TABLE [CashCountLines] ([Conflict] int NOT NULL)");
        await RejectSql("conflicting line table aborts migration", 2714,
            db.Database.ExecuteSqlRawAsync(script));
        Ensure(!await db.Database.SqlQueryRaw<int>(
            "SELECT [Version] AS [Value] FROM [__AmeenSchemaVersions] WHERE [Version]=33").AnyAsync(),
            "A failed CASH11 migration recorded version 33");
        Ensure(!await db.Database.SqlQueryRaw<int>(
            "SELECT 1 AS [Value] FROM sys.tables WHERE name=N'CashCounts'").AnyAsync(),
            "A failed CASH11 migration leaked parent DDL");
        await db.Database.ExecuteSqlRawAsync("DROP TABLE [CashCountLines]");
        await db.Database.ExecuteSqlRawAsync(script);
        await db.Database.ExecuteSqlRawAsync(script);

        Ensure(await db.Database.SqlQueryRaw<int>(
            "SELECT COUNT(*) AS [Value] FROM [__AmeenSchemaVersions] WHERE [Version]=33").SingleAsync() == 1,
            "CASH11 migration not idempotent");
        Ensure(await db.Database.SqlQueryRaw<int>(
            "SELECT COUNT(*) AS [Value] FROM sys.columns WHERE object_id=OBJECT_ID(N'dbo.CashCounts')").SingleAsync() == 12,
            "CASH11 head fields missing");
        Ensure(await db.Database.SqlQueryRaw<int>(
            "SELECT COUNT(*) AS [Value] FROM sys.columns WHERE object_id=OBJECT_ID(N'dbo.CashCountLines')").SingleAsync() == 7,
            "CASH11 line fields missing");
        Ensure(await db.Database.SqlQueryRaw<int>(
            "SELECT COUNT(*) AS [Value] FROM sys.foreign_keys WHERE parent_object_id=OBJECT_ID(N'dbo.CashCounts')").SingleAsync() == 4,
            "CASH11 header references missing");
        Ensure(await db.Database.SqlQueryRaw<int>(
            "SELECT COUNT(*) AS [Value] FROM sys.foreign_keys WHERE parent_object_id=OBJECT_ID(N'dbo.CashCountLines')").SingleAsync() == 2,
            "CASH11 line tenant references missing");
        Ensure(await db.Database.SqlQueryRaw<int>(@"
            SELECT COUNT(*) AS [Value] FROM sys.foreign_keys fk
            WHERE (fk.parent_object_id=OBJECT_ID(N'dbo.CashCounts')
                   AND fk.name<>N'FK_CashCount_Company')
               OR (fk.parent_object_id=OBJECT_ID(N'dbo.CashCountLines')
                   AND fk.name<>N'FK_CashCountLine_Company')").SingleAsync() == 4,
            "CASH11 tenant reference count differs");
        Ensure(await db.Database.SqlQueryRaw<int>(@"
            SELECT COUNT(*) AS [Value] FROM sys.foreign_keys fk
            WHERE fk.parent_object_id IN (OBJECT_ID(N'dbo.CashCounts'),
                                          OBJECT_ID(N'dbo.CashCountLines'))
              AND fk.name NOT IN (N'FK_CashCount_Company',N'FK_CashCountLine_Company')
              AND (SELECT COUNT(*) FROM sys.foreign_key_columns fc
                   WHERE fc.constraint_object_id=fk.object_id)=2
              AND EXISTS (SELECT 1 FROM sys.foreign_key_columns fc
                  JOIN sys.columns col ON col.object_id=fc.parent_object_id
                                        AND col.column_id=fc.parent_column_id
                  WHERE fc.constraint_object_id=fk.object_id AND col.name=N'CompanyId')
            ").SingleAsync() == 4, "CASH11 composite FKs must all include CompanyId");
        Ensure(await db.Database.SqlQueryRaw<int>(
            "SELECT COUNT(*) AS [Value] FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID(N'dbo.CashCounts')").SingleAsync() == 3 &&
            await db.Database.SqlQueryRaw<int>(
            "SELECT COUNT(*) AS [Value] FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID(N'dbo.CashCountLines')").SingleAsync() == 1,
            "CASH11 revision/audit/positive denomination constraints missing");
        Ensure(await db.Database.SqlQueryRaw<int>(@"
            SELECT COUNT(*) AS [Value] FROM sys.computed_columns
            WHERE object_id=OBJECT_ID(N'dbo.CashCountLines')
              AND name=N'CountedValue' AND is_persisted=1").SingleAsync() == 1,
            "CASH11 counted amount must be generated by SQL");

        // EF is deliberately fail-closed until an authorized variance workflow
        // can derive and verify a ledger snapshot for the count.
        var now = new DateTimeOffset(2026, 11, 3, 0, 0, 0, TimeSpan.Zero);
        var probe = new CashCount(Guid.NewGuid(), null, "Unreviewed",
            Guid.NewGuid(), now, Guid.NewGuid(), "test", now);
        db.Add(probe);
        await RejectDomain("cash_count_policy_unavailable", () => db.SaveChangesAsync());
        db.Entry(probe).State = EntityState.Detached;
        var lineProbe = new CashCountLine(Guid.NewGuid(), Guid.NewGuid(), 2m, 3);
        db.Add(lineProbe);
        await RejectDomain("cash_count_policy_unavailable", () => db.SaveChangesAsync());
        db.Entry(lineProbe).State = EntityState.Detached;
        Console.WriteLine("  SQL PASS CASH11-01 atomic/idempotent schema 033, tenant FKs, computed values, EF fail-closed");
    }

    public static async Task Guard(ErpDbContext db, Guid companyId, Guid cashBoxId, Guid branchId)
    {
        var counterId = await db.Set<Membership>().Where(x => x.CompanyId == companyId)
            .Select(x => x.Id).FirstAsync();
        var created = new DateTimeOffset(2026, 11, 3, 1, 0, 0, TimeSpan.Zero);
        var cutoff = created.AddMinutes(-15);
        var cashBox = await db.Set<CashBox>().AsNoTracking()
            .SingleAsync(x => x.CompanyId == companyId && x.Id == cashBoxId);
        var audits = await db.Set<AuditEvent>().CountAsync(x => x.CompanyId == companyId);
        var countId = Guid.NewGuid();
        await db.Database.ExecuteSqlInterpolatedAsync($@"
            INSERT INTO [CashCounts] ([CompanyId],[Id],[Version],[BranchId],[State],
                [CashBoxId],[CutoffAt],[CountedByMembershipId],[CreatedBy],[CreatedAt],
                [Revision],[LastModifiedAt])
            VALUES ({companyId},{countId},{Guid.NewGuid()},{branchId},{"Unreviewed"},
                {cashBoxId},{cutoff},{counterId},{"structural-only"},{created},{1},{created})");
        var count = await db.Set<CashCount>().AsNoTracking().SingleAsync(x =>
            x.CompanyId == companyId && x.Id == countId);
        Ensure(count.BranchId == branchId && count.CashBoxId == cashBoxId &&
            count.CountedByMembershipId == counterId && count.CutoffAt == cutoff &&
            count.State == "Unreviewed" && count.CreatedAt == created &&
            count.LastModifiedAt == created && count.Revision == 1,
            "CASH11 original header field roundtrip failed");

        var lineId = Guid.NewGuid();
        await db.Database.ExecuteSqlInterpolatedAsync($@"
            INSERT INTO [CashCountLines] ([CompanyId],[Id],[Version],
               [CashCountId],[Denomination],[PieceCount])
            VALUES ({companyId},{lineId},{Guid.NewGuid()},{countId},{12.500000m},{4})");
        var savedLine = await db.Set<CashCountLine>().AsNoTracking().SingleAsync(x =>
            x.CompanyId == companyId && x.Id == lineId);
        Ensure(savedLine.Denomination == 12.500000m && savedLine.PieceCount == 4 &&
            savedLine.CountedValue == 50.000000m && savedLine.CashCountId == countId,
            "CASH11 SQL-computed decimal amount is not exact");

        // Repetition of a denomination is not forbidden by the approved analysis;
        // do not invent a unique-denomination policy.
        var secondLineId = Guid.NewGuid();
        await db.Database.ExecuteSqlInterpolatedAsync($@"
            INSERT INTO [CashCountLines] ([CompanyId],[Id],[Version],
               [CashCountId],[Denomination],[PieceCount])
            VALUES ({companyId},{secondLineId},{Guid.NewGuid()},{countId},{12.500000m},{1})");
        Ensure(await db.Set<CashCountLine>().Where(x => x.CompanyId == companyId &&
            x.CashCountId == countId).SumAsync(x => x.CountedValue) == 62.500000m,
            "CASH11 independent lines do not aggregate exact decimal counts");

        var unknown = Guid.NewGuid();
        await RejectSql("foreign box", 547,
            db.Database.ExecuteSqlInterpolatedAsync(
                $"UPDATE [CashCounts] SET [CashBoxId]={unknown} WHERE [CompanyId]={companyId} AND [Id]={countId}"));
        await RejectSql("foreign counter", 547,
            db.Database.ExecuteSqlInterpolatedAsync(
                $"UPDATE [CashCounts] SET [CountedByMembershipId]={unknown} WHERE [CompanyId]={companyId} AND [Id]={countId}"));
        await RejectSql("foreign branch", 547,
            db.Database.ExecuteSqlInterpolatedAsync(
                $"UPDATE [CashCounts] SET [BranchId]={unknown} WHERE [CompanyId]={companyId} AND [Id]={countId}"));
        await RejectSql("negative revision", 547,
            db.Database.ExecuteSqlInterpolatedAsync(
                $"UPDATE [CashCounts] SET [Revision]={0} WHERE [CompanyId]={companyId} AND [Id]={countId}"));
        await RejectSql("invalid audit sequence", 547,
            db.Database.ExecuteSqlInterpolatedAsync(
                $"UPDATE [CashCounts] SET [LastModifiedAt]={created.AddDays(-1)} WHERE [CompanyId]={companyId} AND [Id]={countId}"));
        await RejectSql("blank count state", 547,
            db.Database.ExecuteSqlInterpolatedAsync(
                $"UPDATE [CashCounts] SET [State]={"   "} WHERE [CompanyId]={companyId} AND [Id]={countId}"));
        await RejectSql("negative pieces", 547,
            db.Database.ExecuteSqlInterpolatedAsync(
                $"UPDATE [CashCountLines] SET [PieceCount]={-1} WHERE [CompanyId]={companyId} AND [Id]={lineId}"));
        await RejectSql("zero denomination", 547,
            db.Database.ExecuteSqlInterpolatedAsync(
                $"UPDATE [CashCountLines] SET [Denomination]={0m} WHERE [CompanyId]={companyId} AND [Id]={lineId}"));
        await RejectSql("unknown count owner", 547,
            db.Database.ExecuteSqlInterpolatedAsync(
                $"UPDATE [CashCountLines] SET [CashCountId]={unknown} WHERE [CompanyId]={companyId} AND [Id]={lineId}"));
        await RejectSql("parent with child rows cannot be deleted", 547,
            db.Database.ExecuteSqlInterpolatedAsync(
                $"DELETE FROM [CashCounts] WHERE [CompanyId]={companyId} AND [Id]={countId}"));

        // Every rejected statement is atomic. Neither the cash box nor any
        // ledger, audit, outbox event or actual available balance is changed.
        await CashUnauthorizedEfMutationSqlIntegration.RejectUpdateAndDelete(
            db, count, "cash_count_policy_unavailable");
        await CashUnauthorizedEfMutationSqlIntegration.RejectUpdateAndDelete(
            db, savedLine, "cash_count_policy_unavailable");

        var after = await db.Set<CashCount>().AsNoTracking().SingleAsync(x =>
            x.CompanyId == companyId && x.Id == countId);
        var cashBoxAfter = await db.Set<CashBox>().AsNoTracking()
            .SingleAsync(x => x.CompanyId == companyId && x.Id == cashBoxId);
        Ensure(after.Revision == 1 && after.BranchId == branchId &&
            after.State == "Unreviewed" && after.CashBoxId == cashBoxId &&
            after.CreatedAt == created && after.LastModifiedAt == created &&
            cashBoxAfter.Version == cashBox.Version &&
            cashBoxAfter.Revision == cashBox.Revision &&
            cashBoxAfter.BalanceLimit == cashBox.BalanceLimit &&
            await db.Set<AuditEvent>().CountAsync(x => x.CompanyId == companyId) == audits,
            "CASH11 rejected SQL mutation leaked count, cashbox or audit changes");
        Ensure((await db.Set<CashCountLine>().AsNoTracking().SingleAsync(x =>
            x.CompanyId == companyId && x.Id == lineId)).CountedValue == 50m,
            "CASH11 rejected line update changed amount");

        await db.Database.ExecuteSqlInterpolatedAsync(
            $"DELETE FROM [CashCountLines] WHERE [CompanyId]={companyId} AND [CashCountId]={countId}");
        await db.Database.ExecuteSqlInterpolatedAsync(
            $"DELETE FROM [CashCounts] WHERE [CompanyId]={companyId} AND [Id]={countId}");
        Ensure(!await db.Set<CashCount>().AnyAsync() &&
            !await db.Set<CashCountLine>().AnyAsync(),
            "CASH11 disposable fixture was not cleaned");
        Console.WriteLine("  SQL PASS CASH11-01 exact count amounts, header/line composite FKs, atomic rejection and zero cash impact");
    }

    private static async Task RejectSql(string name, int expectedCode, Task<int> command)
    {
        try { await command; }
        catch (SqlException ex) when (ex.Number == expectedCode ||
            (expectedCode == 2714 && ex.Errors.Cast<SqlError>().Any(e => e.Number == expectedCode))) { return; }
        throw new Exception("CASH11 SQL must reject: " + name);
    }

    private static async Task RejectDomain(string error, Func<Task<int>> action)
    {
        try { await action(); }
        catch (BusinessException e) when (e.Code == error) { return; }
        throw new Exception("CASH11 EF must reject: " + error);
    }

    private static void Ensure(bool ok, string reason)
    {
        if (!ok) throw new Exception(reason);
    }
}
